// Builds compass/js/worldmap.js: a simplified Mercator world map (Natural Earth 1:50m)
// plus the projection, so the game can place cities on the same coordinates.
// Input (download first): https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
// Usage: node scripts/build_worldmap.js countries-50m.json compass/js/worldmap.js
const fs = require('fs');
const [, , topoPath, outPath] = process.argv;
const topo = JSON.parse(fs.readFileSync(topoPath, 'utf8'));

const WIDTH = 1000, LAT_TOP = 84, LAT_BOTTOM = -60, TOL = 0.6, MIN_PX_AREA = 1.5;
const K = WIDTH / 360;
const mercY = lat => {
  const c = Math.max(-85, Math.min(85, lat)) * Math.PI / 180;
  return Math.log(Math.tan(Math.PI / 4 + c / 2)) * 180 / Math.PI;
};
const TOP = mercY(LAT_TOP);
const HEIGHT = Math.round((TOP - mercY(LAT_BOTTOM)) * K);
const project = (lon, lat) => [(lon + 180) * K, (TOP - mercY(lat)) * K];

// Minimal TopoJSON decoding (quantized arcs)
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map(arc => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]]; });
});
const arcPoints = i => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ring = idx => idx.reduce((pts, i, k) => pts.concat(k === 0 ? arcPoints(i) : arcPoints(i).slice(1)), []);
const polygons = g => (g.type === 'Polygon' ? [g.arcs.map(ring)] : g.type === 'MultiPolygon' ? g.arcs.map(p => p.map(ring)) : []);

const ringArea = pts => {
  let a = 0;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) a += (pts[j][0] + pts[i][0]) * (pts[j][1] - pts[i][1]);
  return Math.abs(a / 2);
};
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    let maxD = 0, idx = -1;
    const [ax, ay] = pts[s], [bx, by] = pts[e];
    const len = Math.hypot(bx - ax, by - ay) || 1e-9;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len;
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > tol && idx > 0) { keep[idx] = 1; stack.push([s, idx], [idx, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}

let d = '';
for (const g of topo.objects.countries.geometries) {
  if (g.properties.name === 'Antarctica') continue;
  for (const poly of polygons(g)) {
    for (const raw of poly) {
      // A ring that crosses the antimeridian jumps from +180 to -180; draw it twice,
      // shifted east and west, and let the map's viewBox clip what falls outside
      const wraps = raw.some((pt, i) => i > 0 && Math.abs(pt[0] - raw[i - 1][0]) > 180);
      const variants = wraps
        ? [raw.map(([lon, lat]) => [lon < 0 ? lon + 360 : lon, lat]), raw.map(([lon, lat]) => [lon > 0 ? lon - 360 : lon, lat])]
        : [raw];
      for (const r of variants) {
        const px = r.map(([lon, lat]) => project(lon, lat));
        if (ringArea(px) < MIN_PX_AREA) continue;
        // Closed ring: split at the point farthest from the start before simplifying
        let far = 0, farD = -1;
        px.forEach(([x, y], i) => { const dd = Math.hypot(x - px[0][0], y - px[0][1]); if (dd > farD) { farD = dd; far = i; } });
        const sp = simplify(px.slice(0, far + 1), TOL).concat(simplify(px.slice(far), TOL).slice(1));
        if (sp.length < 4) continue;
        d += 'M' + sp.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z';
      }
    }
  }
}

const out = `// Generated by scripts/build_worldmap.js from Natural Earth 1:50m (public domain). Do not edit by hand.
// Mercator, ${WIDTH}×${HEIGHT}, latitudes ${LAT_TOP}°N to ${-LAT_BOTTOM}°S, Antarctica omitted.
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
const K = ${WIDTH} / 360;
const mercY = lat => {
  const c = Math.max(-85, Math.min(85, lat)) * Math.PI / 180;
  return Math.log(Math.tan(Math.PI / 4 + c / 2)) * 180 / Math.PI;
};
const TOP = mercY(${LAT_TOP});
// [x, y] in map units for a latitude/longitude in degrees
export const project = (lat, lng) => [(lng + 180) * K, (TOP - mercY(lat)) * K];
export const LAND_PATH = '${d}';
`;
fs.writeFileSync(outPath, out);
console.log(`${WIDTH}x${HEIGHT}, path ${(d.length / 1024).toFixed(0)} KB`);
